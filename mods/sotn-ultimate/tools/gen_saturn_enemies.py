"""Saturn port: the Saturn's 26 new enemy records (EnemyDefs 400-425).

The Saturn's g_EnemyDefs (GAME.PRG 0x06080288, 0x28-byte records, big-endian)
keeps the PS1's 400 records and appends 26 for its new enemies: the
Underground Garden's and the Cursed Prison's, Maria and their sub-hitboxes.
They are appended to DRA's table with the same ids (src/config_us.h), so the
Saturn's TekiInit ids port as they are. Stats are copied unchanged (hitbox
widths are stored in PS1 units: the Saturn's TekiInit widens them by 5/4);
drops are re-encoded for the PS1's item numbering (the Saturn inserted hand
and body items). The Saturn names are katakana; these are English names.

Writes src/dra/gen/us/enemydefs_mod.h.
"""
import os
import re
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
GAME = os.path.join(ROOT, "disks/saturn/GAME.PRG")
GEN = os.path.join(ROOT, "src/dra/gen/us")
GAME_BASE = 0x06066000
ENEMY_DEFS = 0x06080288
ACCESSORIES = 0x190A0  # file offset, 32-byte records
FIRST, COUNT = 400, 26
SAT_NUM_HAND = 176  # Saturn combined ids: hand id, or 176 + body id
NUM_HAND = 169      # PS1 NUM_HAND_ITEMS
MOD_DROP_HAND_BASE = NUM_HAND + 93  # include/game.h, NUM_HAND + BODY_ITEMS_CAP

NAMES = {
    0x190: "Gargoyle", 0x191: "Copper Armor", 0x192: "Ifrit",
    0x194: "Skeleton Leader", 0x195: "Gardener", 0x196: "Human Face Tree",
    0x198: "Maria", 0x19D: "Water Leaper", 0x19E: "Man Eater",
    0x19F: "Gargoyle", 0x1A0: "Gargoyle", 0x1A1: "Specter",
    0x1A2: "Will O' Wisp", 0x1A4: "Skel. Breeder", 0x1A5: "Skeleton Beast",
    0x1A7: "Wight", 0x1A8: "Wraith", 0x1A9: "Skel. Guardian",
}

ELEMENTS = [(0x20, "ELEMENT_UNK_1")]

game = open(GAME, "rb").read()


def ps1_accessories():
    out = []
    for line in open(os.path.join(GEN, "accessories.h")):
        m = re.match(r"/\* 0x([0-9A-F]+) \*/ \{.*, (\d+), (\d+), (\d+)\},$", line.strip())
        if m:
            out.append((int(m.group(1), 16), int(m.group(2)), int(m.group(3)), int(m.group(4))))
    return out


PS1_ACC = ps1_accessories()


def body_item(b):
    """Saturn body id -> PS1 body id, matched by icon, palette and type."""
    o = ACCESSORIES + b * 32
    icon, pal, kind = struct.unpack_from(">HHH", game, o + 0x18)
    hits = [i for i, ic, p, k in PS1_ACC if (ic, p, k) == (icon, pal, kind)]
    assert len(hits) == 1, ("Saturn body item", b, icon, pal, hits)
    return hits[0]


def hand_item(h):
    """Saturn hand id -> PS1 combined drop id (new items: MOD_DROP_HAND_BASE+)."""
    new = {70: 0, 71: 1, 169: 2, 172: 3, 173: 4, 174: 5, 175: 6}
    if h in new:
        return MOD_DROP_HAND_BASE + new[h]
    if h < 70:
        return h
    if h < 169:
        return h - 2
    return h - 3


def drop(v):
    if v < 0x80:
        return v  # hearts, money and the other prizes
    c = v - 0x80
    if c < SAT_NUM_HAND:
        return 0x80 + hand_item(c)
    return 0x80 + NUM_HAND + body_item(c - SAT_NUM_HAND)


def main():
    lines = []
    for i in range(FIRST, FIRST + COUNT):
        r = struct.unpack_from(">IhhHhHHHHHHHHHHHBBI", game, ENEMY_DEFS - GAME_BASE + i * 0x28)
        (_, hp, atk, elem, df, hbs, weak, strong, immune, absorb, level, exp,
         rare, unc, rare_rate, unc_rate, w, h, flags) = r
        name = NAMES.get(i, "")
        lines.append(
            "/* 0x%03X */ {_S(\"%s\"), %d, %d, 0x%04X, %d, %d, 0x%04X, 0x%04X, 0x%04X, "
            "0x%04X, %d, %d, 0x%03X, 0x%03X, %d, %d, %d, %d, 0x%08X},"
            % (i, name, hp, atk, elem, df, hbs, weak, strong, immune, absorb,
               level, exp, drop(rare), drop(unc), rare_rate, unc_rate, w, h, flags))
    with open(os.path.join(GEN, "enemydefs_mod.h"), "w") as f:
        f.write("// Generated by mods/sotn-ultimate/tools/gen_saturn_enemies.py, do not edit\n")
        f.write("// clang-format off\n" + "\n".join(lines) + "\n// clang-format on\n")
    print("wrote enemydefs_mod.h:", COUNT, "Saturn enemy records")


if __name__ == "__main__":
    main()
