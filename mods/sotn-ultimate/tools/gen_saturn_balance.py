"""Saturn port: the Saturn's gameplay balance changes, as a runtime patch list.

The DRA tables keep the PS1 (retail) values; src/dra/game_handlers.c
ModApplyBalance writes either the PS1 or the Saturn value of every field
listed here each frame of play, from the Player Select "Balance" row
(include/game.h MOD_FLAG_PS1_BALANCE: set = PS1, clear = Saturn).

Every entry is checked against the retail DRA.BIN (PS1 value) and the Saturn
GAME.PRG (Saturn value), so a wrong offset or id fails loudly. The list is the
complete set of Saturn equipment/enemy record changes that are not item
renumbering (unk17/specialMove +7), Saturn food format (weaponId 255 /
unk13 128) or Saturn-only items (feat/balance_opt/eqdiff.py has the full
diff). Writes src/dra/gen/us/mod_balance.h.
Run from mods/sotn-ultimate/tools/build_disc.sh.
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
DRA = open(os.path.join(ROOT, "disks/us/DRA.BIN"), "rb").read()
GAME = open(os.path.join(ROOT, "disks/saturn/GAME.PRG"), "rb").read()
DST = os.path.join(ROOT, "src/dra/gen/us/mod_balance.h")

# (PS1 table offset in DRA.BIN, Saturn table offset in GAME.PRG, stride)
EQ = (0x4B04, 0x16250, 0x34)
EN = (0x8900, 0x1A288, 0x28)
EQ_FIELDS = {"enemyInvincibilityFrames": (0x1A, "B"), "unk14": (0x14, "B"),
             "lockDuration": (0x15, "B"), "comboMain": (0x20, "I")}
EN_FIELDS = {"attack": (0x06, "h"), "rareItemDropRate": (0x1E, "H"),
             "flags": (0x24, "I")}

IFRAMES = [104, 105, 106, 108, 110, 111, 112, 113, 115, 116, 117, 118, 122,
           123, 124, 125, 126, 139, 140, 141, 168]
# (table, PS1 / mod id, Saturn id, field, PS1 value, Saturn value, comment)
CHANGES = [("EQ", i, i + (2 if i < 169 else 0) + (1 if i >= 168 else 0),
            "enemyInvincibilityFrames", 14, 21, None) for i in IFRAMES]
CHANGES += [
    ("EQ", 116, 118, "unk14", 2, 5, "Terminus Est"),
    ("EQ", 122, 124, "unk14", 2, 6, "Mourneblade"),
    ("EQ", 127, 129, "lockDuration", 18, 16, "Great Sword"),
    ("EQ", 124, 126, "comboMain", 0x3FFE, 0x7FFE, "Mablung Sword"),
    ("EQ", 4, 4, "comboMain", 0x3FFE, 0x7FFE, "Shield rod"),
    ("EN", 0x133, 0x133, "attack", 25, 45, "boss Richter"),
    ("EN", 0x094, 0x094, "rareItemDropRate", 4, 8, "Fire Warg"),
    ("EN", 0x05D, 0x05D, "flags", 0xAA00D410, 0x9A00D410, "Spear Guard"),
]

out = ["// generated by mods/sotn-ultimate/tools/gen_saturn_balance.py: {table field, PS1, Saturn}\n"]
for tbl, pid, sid, field, ps1, sat, note in CHANGES:
    (pbase, sbase, stride), fields = (EQ, EQ_FIELDS) if tbl == "EQ" else (EN, EN_FIELDS)
    off, fmt = fields[field]
    got_p = struct.unpack_from("<" + fmt, DRA, pbase + pid * stride + off)[0]
    got_s = struct.unpack_from(">" + fmt, GAME, sbase + sid * stride + off)[0]
    if fmt == "I" or fmt == "i":
        got_p &= 0xFFFFFFFF; got_s &= 0xFFFFFFFF
    assert (got_p, got_s) == (ps1, sat), (tbl, pid, field, got_p, got_s)
    if tbl == "EQ":  # same item on both (icon matches)
        assert DRA[pbase + pid * stride + 0x2C:pbase + pid * stride + 0x2E] == \
            GAME[sbase + sid * stride + 0x2C:sbase + sid * stride + 0x2E][::-1], pid
    out.append("MOD_BAL_%s(0x%03X, %s, 0x%X, 0x%X),%s\n" % (
        tbl, pid, field, ps1, sat, " // " + note if note else ""))
text = "".join(out)
if not os.path.exists(DST) or open(DST).read() != text:
    open(DST, "w").write(text)
print("mod_balance.h: %d Saturn balance fields" % len(CHANGES))
