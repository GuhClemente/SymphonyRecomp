"""Saturn port mod: Richter's and Maria's horse ride into the castle (NO3).

On the Saturn, the Entrance's opening run (STAGE_0X entity 0x4E, 0x060DC040)
is Alucard's run for Alucard only: Richter and Maria ride in on a horse
(0x060DC300), leap off at the gate and leave the horse rearing there. The
whole scene is one sprite, the horse with its rider (the player is hidden):
bank 0x060F3DD4 (34 images, 5 palettes), frames 0x060F3CCC:
  1-5 Richter galloping (brown horse), 6-7 the riderless horse rearing,
  8 Richter leaping; 9-13 Maria galloping (white horse), 14-22 her leap,
  23-24 her in the air; 25-30 Richter in his alternate costume (1-5, 8).
Palettes: 0 brown horse, 1 Richter, 2 white horse, 3-4 Maria; the rearing
horse takes palette offset 2 for Maria's white horse.

NO3 is a retail overlay whose data section must not move, so everything here
is rodata, in src/st/no3/mod_horse.h (tables included from e_red_door.c,
whose .rodata the link script keeps; the code is in e_outdoor_ents.c):
  - the art: narrowed to PSX proportions (mods/sotn-ultimate/tools/saturn_sprites.py) and
    packed into 128x128 4bpp quadrants of the stage sprite pages (tpages
    18-19, VRAM x 128-255, y 256-511). The ride's room (NO3 room 18, the
    18-screen road) loads no sprite graphics bank: its entities draw from the
    tile pages (the owl and leaves, ANIMSET_OVL(1), tpages 14-15) or with
    their own primitives, so those quadrants are free there in every mode.
    The quadrants are stored as LZSS strips of STRIP_ROWS rows (the MARIA.BIN
    format, unpacked by the ride's code into a 2 KB buffer, one strip per
    frame while the scene is still off-screen);
  - the frames: sprite bank HORSE_ANIMSET (NO3's spriteBanks 10+ are empty;
    the code points slot 10 at them at run time), indexed as the Saturn's;
  - the palettes: the bank's 5, uploaded at run time to 0x2D9-0x2DD (a gap
    in NO3's palette list: Death's end at 0x2D8, the cutscene's start at
    0x2E0).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import saturn_sprites  # noqa: E402
from saturn_sprites import SaturnStage, PsxSpriteSheet  # noqa: E402
from gen_mar_assets import lzss, unlzss  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
SAT = os.path.join(ROOT, "disks/saturn")
OUT = os.path.join(ROOT, "src/st/no3/mod_horse.h")
BANK, FRAMES = 0x060F3DD4, 0x060F3CCC
NFRAMES = 30
QUADRANTS = [(t, q) for t in (18, 19) for q in range(4)]
PAL_BASE = 0x2D9
HORSE_ANIMSET = 10
STRIP_ROWS = 32  # 2 KB of 4bpp quadrant rows per strip


def main():
    st = SaturnStage(os.path.join(SAT, "STAGE_0X.PRG"), os.path.join(SAT, "STAGE_0X.CHR"),
                     os.path.join(SAT, "0.BIN"))
    # images packed trimmed to their content
    saturn_sprites.TRIM_BANKS[BANK] = set()

    def fill(sheet):
        sheet.palette_block(st, BANK)
        return [sheet.frame(st, BANK, FRAMES, f) for f in range(1, NFRAMES + 1)]

    probe = PsxSpriteSheet(QUADRANTS * 2, PAL_BASE)
    fill(probe)
    sheet = PsxSpriteSheet(QUADRANTS, PAL_BASE)
    sheet.prepack(st, probe.requests)
    frames = fill(sheet)
    nq = sheet.used_quadrants()
    assert len(sheet.cluts) == 5 and PAL_BASE + 5 <= 0x2E0, sheet.cluts

    strips = []  # (vram x, vram y, rows, packed)
    for q in range(nq):
        rows = max(y + h for qq, _, y, _, h in sheet.placed.values() if qq == q)
        px = sheet.quadrant_pixels(q)
        tpage, quad = sheet.quadrants[q]
        vx = (tpage & 15) * 64 + (quad & 1) * 32
        vy = (tpage >> 4) * 256 + (quad >> 1) * 128
        for r0 in range(0, rows, STRIP_ROWS):
            n = min(STRIP_ROWS, rows - r0)
            raw = px[r0 * 64:(r0 + n) * 64]
            packed = lzss(raw)
            assert unlzss(packed, len(raw)) == raw
            strips.append((vx, vy + r0, n, packed))

    with open(OUT, "w") as f:
        f.write("// Generated by mods/sotn-ultimate/tools/gen_no3_horse.py, do not edit\n// clang-format off\n")
        f.write("// Richter's and Maria's horse ride (Saturn STAGE_0X bank 0x%08X)\n" % BANK)
        f.write("#define MOD_HORSE_BANK %d\n" % HORSE_ANIMSET)
        f.write("#define MOD_HORSE_ANIMSET ANIMSET_OVL(%d)\n" % HORSE_ANIMSET)
        f.write("#define MOD_HORSE_PAL 0x%X\n" % PAL_BASE)
        f.write("#define MOD_HORSE_NPALS %d\n" % len(sheet.cluts))
        f.write("#define MOD_HORSE_NSTRIPS %d\n" % len(strips))
        f.write("#define MOD_HORSE_STRIP_BYTES %d\n" % (STRIP_ROWS * 64))
        f.write("// a strip: packed offset, VRAM x, y (halfwords, rows), rows\n")
        f.write("typedef struct {\n    u32 off;\n    u16 x;\n    u16 y;\n    u16 rows;\n"
                "    u16 pad;\n} ModHorseStrip;\n")
        f.write("#ifdef MOD_HORSE_TABLES\n")
        f.write("#ifndef MOD_RO\n#define MOD_RO __attribute__((section(\".rodata\")))\n#endif\n")
        blob = b"".join(s[3] for s in strips)
        f.write("u8 g_ModHorseLz[] MOD_RO = {\n")
        for k in range(0, len(blob), 32):
            f.write("    " + ",".join("%d" % b for b in blob[k:k + 32]) + ",\n")
        f.write("};\n")
        f.write("ModHorseStrip g_ModHorseStrips[] MOD_RO = {\n")
        off = 0
        for vx, vy, n, packed in strips:
            f.write("    {%d, %d, %d, %d, 0},\n" % (off, vx, vy, n))
            off += len(packed)
        f.write("};\n")
        for n, parts in enumerate(frames):
            vals = [len(parts)]
            for p in parts:
                vals += [p["flags"], p["x"], p["y"], p["width"], p["height"], p["clut"],
                         p["tileset"], p["left"], p["top"], p["right"], p["bottom"]]
            vals.append(0)
            if len(vals) & 1:
                vals.append(0)
            f.write("s16 g_ModHorseFrame%d[] MOD_RO = {%s};\n" % (n + 1, ", ".join(map(str, vals))))
        f.write("s16* g_ModHorseSprites[] MOD_RO = {\n    0,\n")
        for n in range(len(frames)):
            f.write("    g_ModHorseFrame%d,\n" % (n + 1))
        f.write("};\n")
        f.write("u16 g_ModHorsePals[] MOD_RO = {\n")
        for pal in sheet.cluts:
            f.write("    " + ", ".join("0x%04X" % c for c in pal) + ",\n")
        f.write("};\n#endif\n// clang-format on\n")
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(sheet, frames, sys.argv[2])
    raw = sum(s[2] * 64 for s in strips)
    print("no3 horse: %d images in %d quadrants, %d strips, %d -> %d bytes packed, %d palettes"
          % (len(sheet.placed), nq, len(strips), raw, len(blob), len(sheet.cluts)))


def preview(sheet, frames, path):
    """the PSX frames as the PS1 draws them (a check sheet)"""
    from PIL import Image
    cw, ch = 160, 120
    img = Image.new("RGB", (cw * 8, ch * 4), (40, 40, 60))
    pages = {sheet.quadrants[q]: sheet.pages[q] for q in range(len(sheet.pages))}
    for n, parts in enumerate(frames):
        ox, oy = (n + 1) % 8 * cw + cw // 2, (n + 1) // 8 * ch + ch - 30
        for p in reversed(parts):  # the first part ends up on top
            page = pages[(p["tileset"] >> 2, p["tileset"] & 3)]
            pal = sheet.cluts[p["clut"] - PAL_BASE]
            for y in range(p["height"]):
                for x in range(p["width"]):
                    v = page[p["top"] + y][p["left"] + x]
                    if v and 0 <= ox + p["x"] + x < cw * 8 and 0 <= oy + p["y"] + y < ch * 4:
                        c = pal[v]
                        img.putpixel((ox + p["x"] + x, oy + p["y"] + y),
                                     ((c & 31) << 3, (c >> 5 & 31) << 3, (c >> 10 & 31) << 3))
    img.save(path)


if __name__ == "__main__":
    main()
