// The release side of the builder's "array" spans (src/build.ts ArraySpan):
// the numeric arrays of a generator's C output, located in the compiled disc
// file (node/c_arrays.ts). An array whose bytes are in a retail PS1 stage
// file as they are is the PS1's own data (a stage copied it): it stays in the
// patch; every other one is blanked there and made again by the builder.
import * as fs from "node:fs";
import * as path from "node:path";
import { arrayBytes, parseCArrays, symbolAddresses } from "./c_arrays.ts";
import { ROOT } from "./util.ts";

export interface ArraySource {
    gen: string; // the converter that makes them
    disc: string; // the compiled file on the disc, e.g. "ST/TE1/TE1.BIN"
    files: string[]; // generated C files (repo paths, or folders: their gen/** and "Generated by" files)
    map: string; // the link map
    base: number; // load address of the file
}

export interface LocatedArray {
    name: string;
    offset: number;
    bytes: Uint8Array;
}

let retail: Buffer[] | null = null;

function retailStageFiles(): Buffer[] {
    if (!retail) {
        retail = [];
        for (const top of ["ST", "BOSS"]) {
            for (const d of fs.readdirSync(path.join(ROOT, "disks/us", top))) {
                for (const f of fs.readdirSync(path.join(ROOT, "disks/us", top, d))) {
                    if (/\.BIN$/i.test(f)) {
                        retail.push(fs.readFileSync(path.join(ROOT, "disks/us", top, d, f)));
                    }
                }
            }
        }
    }
    return retail;
}

function generatedFiles(p: string): string[] {
    const abs = path.join(ROOT, p);
    if (!fs.statSync(abs).isDirectory()) {
        return [abs];
    }
    const out: string[] = [];
    const walk = (d: string): void => {
        for (const e of fs.readdirSync(d, { withFileTypes: true })) {
            const f = path.join(d, e.name);
            if (e.isDirectory()) {
                walk(f);
            } else if (/\.(c|h)$/.test(e.name) &&
                       (f.includes("/gen/") || /Generated by/.test(fs.readFileSync(f, "utf8").slice(0, 200)))) {
                out.push(f);
            }
        }
    };
    walk(abs);
    return out.sort();
}

// the arrays to blank, each checked against the file's bytes (bin: the file
// as on the finished disc)
export function locateArrays(src: ArraySource, bin: Uint8Array): LocatedArray[] {
    const syms = symbolAddresses(path.join(ROOT, src.map), ROOT);
    const ps1 = retailStageFiles();
    const out: LocatedArray[] = [];
    const seen = new Set<string>();
    for (const f of src.files.flatMap(generatedFiles)) {
        for (const a of parseCArrays(f, [path.dirname(f), path.join(ROOT, "include")])) {
            if (seen.has(a.name)) {
                continue;
            }
            seen.add(a.name);
            const bytes = arrayBytes(a);
            const at = (syms.get(a.name) ?? []).map((x) => x - src.base).find((o) =>
                o >= 0 && o + bytes.length <= bin.length && bytes.every((b, i) => bin[o + i] === b));
            if (at === undefined) {
                continue; // not linked (a stale generated file)
            }
            if (bytes.length >= 16 && ps1.some((b) => b.indexOf(bytes) >= 0)) {
                continue; // the PS1's own data
            }
            out.push({ name: a.name, offset: at, bytes });
        }
    }
    return out;
}
