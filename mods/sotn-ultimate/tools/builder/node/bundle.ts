// node mods/sotn-ultimate/tools/builder/node/bundle.ts OUT.js src/a.ts src/b.ts ...
// Strips the TypeScript types (Node's own stripper: no npm) and joins the
// modules into one classic script defining the global SotnBuilder, so the
// page works when opened from a file (no module loading from file://).
// Our modules only use `import { a, b } from "./x.ts"` and `export
// function|const|class|interface|type`.
import * as fs from "node:fs";
import * as path from "node:path";
import { stripTypeScriptTypes } from "node:module";

const [out, ...files] = process.argv.slice(2);
const parts: string[] = [];
const names = files.map((f) => path.basename(f, ".ts"));
const done = new Set<string>();
for (const f of files) {
    let js = stripTypeScriptTypes(fs.readFileSync(f, "utf8"), { mode: "strip" });
    js = js.replace(/^import\s*\{([^}]*)\}\s*from\s*"\.\/([\w]+)\.ts";?\s*$/gm, (_m, list: string, mod: string) => {
        const ids = list.split(",").map((s) => s.trim()).filter((s) => s && !s.startsWith("type "));
        if (ids.length && !done.has(mod)) {
            // the modules run in this order: put mod before this one
            throw new Error(f + ": imports " + mod + ", which is not bundled before it");
        }
        return ids.length ? `const { ${ids.join(", ")} } = __mods[${JSON.stringify(mod)}];` : "";
    });
    if (/^import /m.test(js)) {
        throw new Error(f + ": unsupported import");
    }
    const exported: string[] = [];
    js = js.replace(/^export\s+(async\s+function|function|const|let|class)\s+(\w+)/gm, (_m, kw: string, name: string) => {
        exported.push(name);
        return `${kw} ${name}`;
    });
    if (/^export /m.test(js)) {
        throw new Error(f + ": unsupported export");
    }
    const name = path.basename(f, ".ts");
    done.add(name);
    parts.push(`__mods[${JSON.stringify(name)}] = (() => {\n${js}\nreturn { ${exported.join(", ")} };\n})();`);
}
const body = `// generated by mods/sotn-ultimate/tools/builder/node/bundle.ts from ${names.join(", ")}\n` +
    `var SotnBuilder = (() => {\n"use strict";\nconst __mods = {};\n${parts.join("\n")}\nreturn __mods;\n})();\n`;
fs.writeFileSync(out, body);
console.log("bundle: %s (%d bytes, %d modules)", out, body.length, files.length);
