// node mods/sotn-ultimate/tools/builder/node/cen_sounds.ts cen | cenp-ps1sat
// The build's Saturn-rendered CEN banks (in place of the Python), from the
// extracted discs in disks/:
//   cen: gen_cen_sounds.py's build/us/SD_ZKCEN.VH/.VB, CEN_SD_PS1.bin and
//        src/st/cen/mod_cen_sfx.h (src/cen_sounds.ts)
//   cenp-ps1sat: gen_cenp_sounds.py --ps1sat's build/us/CENP_SD_PS1.bin
//        (src/cenp_sounds.ts)
import * as fs from "node:fs";
import * as path from "node:path";
import { buildCen, CEN_SOUNDS, cenCfgIds } from "../src/cen_sounds.ts";
import { buildCenp, cenpCfgIds } from "../src/cenp_sounds.ts";
import { Dsp } from "../src/dsp.ts";
import { audioModule } from "./audio_cli.ts";
import { ROOT, sfxConfig } from "./util.ts";

const rd = (d: string) => async (p: string): Promise<Uint8Array> => new Uint8Array(fs.readFileSync(path.join(ROOT, d, p)));
const out = (p: string, b: Uint8Array): void => fs.writeFileSync(path.join(ROOT, "build/us", p), b);
const dsp = new Dsp((await audioModule()) as never);
const saturn = { readFile: rd("disks/saturn") };
const what = process.argv[2];
if (what === "cen") {
    const r = await buildCen(audioModule, dsp, saturn, rd("disks/us"), sfxConfig(cenCfgIds()));
    out("SD_ZKCEN.VH", r.vh);
    out("SD_ZKCEN.VB", r.vb);
    out("CEN_SD_PS1.bin", r.ps1);
    const h = ["// Generated by mods/sotn-ultimate/tools/gen_cen_sounds.py, do not edit",
        "// Maria's Saturn sounds in CEN's stage bank (build/us/SD_ZKCEN)",
        ...CEN_SOUNDS.map(([n, sat, id]) => "#define MOD_SFX_" + n + " 0x" + id.toString(16).toUpperCase() +
                          " // Saturn 0x" + sat.toString(16).toUpperCase())].join("\n") + "\n";
    const hp = path.join(ROOT, "src/st/cen/mod_cen_sfx.h");
    if (!fs.existsSync(hp) || fs.readFileSync(hp, "utf8") !== h) {
        fs.writeFileSync(hp, h);
    }
    console.log("cen sounds: %d sounds, rate cap %d", CEN_SOUNDS.length, r.cap);
} else if (what === "cenp-ps1sat") {
    const res = rd("disks/psp");
    const r = await buildCenp(audioModule, dsp, saturn, rd("disks/us"), await res("snd_e/SE/sd_mar2.spk"),
                              await res("sound/SE/sd_mar2.spk"), sfxConfig(cenpCfgIds()));
    out("CENP_SD_PS1.bin", r.ps1);
    console.log("cenp sounds (ps1 sat): 15 clips, rate cap %d", r.satCap);
} else {
    throw new Error("usage: cen_sounds.ts cen | cenp-ps1sat");
}
