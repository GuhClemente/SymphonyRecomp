"""Saturn port mod: the PSP Maria's subweapon drop icons for BIN/MARIA2.BIN.
The PSP's DRA item sprite bank (D_800D0F68, ANIMSET_DRA(3)) has 32 frames
past the PS1's 0xA0: 0xA1-0xC0, the drop animations of her Cardinal, Cat,
Turtle and Dragon (8 frames each: the icon + the PS1's sparkle), drawn from
the PSP item art that her overlay loads into VRAM (items_gfx; the Doll is
in the Bible's place there, so the PSP plays the Bible frames for it).
Copies them from the US UMD's dra.bin into mods/sotn-ultimate/src/maria_psp/mar2_items.h."""
import os
import struct

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
DRA = os.path.join(ROOT, "disks/psp/PSPBIN/dra.bin")
OUT = os.path.join(ROOT, "mods/sotn-ultimate/src/maria_psp/mar2_items.h")
VRAM = 0x090CA700  # the US dra.bin's load address (builder/src/mod_tables.ts)
TABLE = 0x6A628  # D_800D0F68's pointer table there
NAMES = ["CARDINAL", "CAT", "TURTLE", "DRAGON"]

d = open(DRA, "rb").read()
ptrs = struct.unpack_from("<193I", d, TABLE)
assert ptrs[0] == 0 and all(ptrs[1:]), "unexpected PSP D_800D0F68 table"
lines = [
    "// Generated by mods/sotn-ultimate/tools/gen_mar2_items.py, do not edit",
    "// the PSP DRA item sprite frames 0xA1-0xC0 (mods/sotn-ultimate/src/maria_psp/mar2.c)",
    "static s16 g_Mar2ItemFrames[32][24] = {",
]
for n in range(0xA1, 0xC1):
    o = ptrs[n] - VRAM
    count = struct.unpack_from("<h", d, o)[0]
    assert count == 2
    v = struct.unpack_from("<%dh" % (1 + 11 * count), d, o)
    k = n - 0xA1
    lines.append("    {%s, 0}, // 0x%X %s %d" % (", ".join(map(str, v)), n, NAMES[k // 8], k % 8))
lines.append("};")
open(OUT, "w").write("\n".join(lines) + "\n")
print("mar2 items: 32 PSP drop frames -> %s" % os.path.relpath(OUT, ROOT))
